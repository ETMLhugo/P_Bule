/**
 * Formate un nom et une valeur dans un message.
 */
/**
 *
 * @param {string} name nom de l energie
 * @param {number} value la valeur de l energie
 * @returns {string} retourne quelle nom d energie a combien d energie
 */
export function formatResult(name, value) {
  return name + " : " + value;
}
